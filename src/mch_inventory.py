#!/usr/bin/env python3
"""Turn crates/crate-aliases.json into the things that need crate names.

    python3 mch_inventory.py            # write hosts snippet + Prometheus SD
    python3 mch_inventory.py --check    # resolve each name, report

Generates:

    crates/hosts.snippet               # append to /etc/hosts (one line per crate)
    deploy/prometheus/crates.yml       # file_sd: one target per exporter

Why a hosts snippet: `ipmitool -H <name>` uses the system resolver, so once the
name is in /etc/hosts it works for scan_mch.py and mch_exporter.py with no code
change. Prometheus never resolves the crate name -- it scrapes the exporter --
so that address stays `mch-exporter:<port>` (one docker alias, nine ports).
"""
import argparse
import json
import os
import re
import socket
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # src/..
CRATES = os.path.join(ROOT, "crates")
INVENTORY = os.path.join(ROOT, "crates", "crate-aliases.json")
HOSTS = os.path.join(ROOT, "crates", "hosts.snippet")
SD = os.path.join(ROOT, "deploy", "prometheus", "crates.yml")
SD_FAST = os.path.join(ROOT, "deploy", "prometheus", "crates-fast.yml")
# Ports are derived, never written by hand: 9290 + the trailing number in the
# crate name (CD1 -> 9291), else 9290 (TVT). Collisions are resolved in file
# order, so the mapping is deterministic for a given list of crates.
BASE_PORT = int(os.environ.get("MCH_PORT_BASE", "9290"))


def load():
    from mch_names import load as load_crates
    crates = load_crates(INVENTORY)
    seen = set()
    for c in crates:
        if c["name"] in seen:
            raise SystemExit("duplicate crate name: %s" % c["name"])
        seen.add(c["name"])
        # c["port"] is derived by mch_names.load()
    return crates


def write_hosts(crates):
    lines = ["# generated by mch_inventory.py -- append to /etc/hosts",
             "# <ip>            <name>"]
    for c in crates:
        lines.append("%-16s %s" % (c["ip"], c["name"]))
    with open(HOSTS, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %s" % HOSTS)


def write_env(crates):
    """One env file per crate: the systemd template reads the port from here,
    so `systemctl --user enable --now mch-exporter@CD2` needs no other edit."""
    for c in crates:
        d = os.path.join(CRATES, c["name"])
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "env"), "w") as fh:
            fh.write("MCH_PORT=%d\n" % c["port"])
    print("wrote %d crates/<name>/env" % len(crates))


def _sd_block(crates):
    lines = ["# generated by mch_inventory.py -- file_sd for Prometheus",
             "# the exporter runs on this host, so one alias + one port per crate"]
    for c in crates:
        lines += [
            "- targets: ['mch-exporter:%d']" % c["port"],
            "  labels:",
            "    crate: %s" % c["name"],
            "    site: %s" % c["site"],
        ]
    return lines


def write_sd(crates):
    """Two files, because Prometheus sets scrape_interval per job, not per
    target: crates with a small sweep ("fast": true) get their own job so they
    are not held to the slow crates' 180 s."""
    fast = [c for c in crates if c.get("fast")]
    slow = [c for c in crates if not c.get("fast")]
    for path, group, label in ((SD, slow, "mtca"), (SD_FAST, fast, "mtca-fast")):
        with open(path, "w") as fh:
            fh.write("\n".join(_sd_block(group)) + "\n")
        print("wrote %s (%d crates -> job %s)" % (path, len(group), label))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="resolve the names")
    args = ap.parse_args()
    crates = load()
    if args.check:
        return 1 if check(crates) else 0
    write_hosts(crates)
    write_sd(crates)
    write_env(crates)
    print("\nnext: sudo sh -c 'cat crates/hosts.snippet >> /etc/hosts'")
    return 0


if __name__ == "__main__":
    sys.exit(main())
